"""One-off builder for data/questions.json. C versions are generated as option permutations of O."""
import json
from pathlib import Path

def v(stem, options, ans, **vars_):
    d = {"stem": stem, "options": options, "answer": ans}
    if vars_:
        d["vars"] = vars_
    return d

Q = []

def add(id_, subject, O, A, B, perm, check=None):
    opts = [O["options"][i] for i in perm]
    C = {"stem": O["stem"], "options": opts, "answer": perm.index(O["answer"])}
    if "vars" in O:
        C["vars"] = O["vars"]
    q = {"id": id_, "subject": subject, "versions": {"O": O, "A": A, "B": B, "C": C}}
    if check:
        q["check"] = check
    Q.append(q)

